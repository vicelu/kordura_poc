const dictionaries: Record<Lang, Record<Key, string>> = { en, hr }

type T = (key: Key, vars?: Record<string, string | number>) => string

interface I18n {
  lang: Lang
  locale: string
  setLang: (l: Lang) => void
  t: T
}

const Ctx = createContext<I18n | null>(null)

const initialLang = (): Lang => {
  try {
    const stored = localStorage.getItem('kordura.lang')
    if (stored === 'en' || stored === 'hr') return stored
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('hr') ? 'hr' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    document.documentElement.lang = l
    try {
      localStorage.setItem('kordura.lang', l)
    } catch {
      /* storage unavailable */
    }
  }, [])
  const value = useMemo<I18n>(() => {
    const dict = dictionaries[lang]
    const t: T = (key, vars) => {
      let s = dict[key] ?? en[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
      return s
    }
    return { lang, locale: lang === 'hr' ? 'hr-HR' : 'en-GB', setLang, t }
  }, [lang, setLang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n outside provider')
  return ctx
}
